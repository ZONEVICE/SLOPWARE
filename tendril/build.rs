//! Build script: embeds the front end and checks the version.
//!
//! 1. `version.txt` must hold the same version as `Cargo.toml`.
//! 2. Every `*.gz` file under `web/dist/` (produced by `node web/build.mjs`,
//!    which bundles with esbuild and gzips each output) becomes an entry of
//!    `ASSETS`, a sorted table compiled into the binary with `include_bytes!`.
//!    The URL is the path without `.gz`; the content type is decided here; the
//!    ETag comes from the CRC-32 and size already stored in each gzip trailer.
//!    Files under a `chunks/` directory carry a content hash in their name and
//!    are marked immutable.
//!
//! 3. A warning when `web/dist` is older than the front end's sources: it is
//!    a build output, so a synced or checked-out tree can bring new sources
//!    without it, and the binary would quietly embed the previous interface.
//!
//! `TENDRIL_WEB_DIST` points the build at another directory.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::SystemTime;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));

    let version = fs::read_to_string(manifest.join("version.txt")).expect("version.txt is missing");
    let package = env::var("CARGO_PKG_VERSION").expect("CARGO_PKG_VERSION");
    if version.trim() != package {
        panic!("version.txt says {:?} but Cargo.toml says {package:?}; keep them equal", version.trim());
    }
    println!("cargo:rerun-if-changed=version.txt");

    println!("cargo:rerun-if-env-changed=TENDRIL_WEB_DIST");
    let dist = env::var_os("TENDRIL_WEB_DIST").map(PathBuf::from).unwrap_or_else(|| manifest.join("web").join("dist"));
    println!("cargo:rerun-if-changed={}", dist.display());
    if !dist.join("index.html.gz").is_file() {
        panic!(
            "\n\nThe front end is not built: {} has no index.html.gz.\n\
             Run ./build.sh (Linux) or ./build.ps1 (Windows), or by hand:\n\
             \n    npm --prefix web ci\n    node web/build.mjs\n\n",
            dist.display()
        );
    }

    // Every `node web/build.mjs` rewrites the whole of web/dist, so the time
    // of index.html.gz is the time of the last front-end build. Watching the
    // sources re-runs this check when they change (and recompiles the crate).
    let web = manifest.join("web");
    let sources = [web.join("src"), web.join("build.mjs"), web.join("package.json"), web.join("package-lock.json")];
    for source in &sources {
        println!("cargo:rerun-if-changed={}", source.display());
    }
    let built = fs::metadata(dist.join("index.html.gz")).and_then(|m| m.modified()).ok();
    if let (Some(built), Some((changed, path))) = (built, newest(&sources))
        && changed > built
    {
        let short = |p: &Path| p.strip_prefix(&manifest).unwrap_or(p).display().to_string();
        println!(
            "cargo:warning={} is older than {}: this build embeds an out-of-date front end. \
             Run `node web/build.mjs` (or build.sh / build.ps1 without -SkipWeb), then build again.",
            short(&dist),
            short(&path)
        );
    }

    let mut files = Vec::new();
    collect(&dist, &dist, &mut files);
    files.sort();

    let mut out =
        String::from("// @generated by build.rs from web/dist. Do not edit.\npub static ASSETS: &[Asset] = &[\n");
    for (url, path) in files {
        let data = fs::read(&path).expect("read asset");
        assert!(data.len() >= 18 && data[0] == 0x1f && data[1] == 0x8b, "{} is not gzip", path.display());
        let n = data.len();
        let crc = u32::from_le_bytes(data[n - 8..n - 4].try_into().unwrap());
        let size = u32::from_le_bytes(data[n - 4..].try_into().unwrap());
        let mime = content_type(&url);
        let immutable = url.contains("/chunks/");
        let file = path.to_string_lossy();
        out.push_str(&format!(
            "    Asset {{ path: {url:?}, mime: {mime:?}, etag: \"\\\"{crc:08x}-{size:x}\\\"\", immutable: {immutable}, size: {size}, gzip: include_bytes!({file:?}) }},\n"
        ));
    }
    out.push_str("];\n");
    let target = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("assets.rs");
    fs::write(target, out).expect("write assets.rs");
}

/// (URL path, file) for every `.gz` file below `dir`.
fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let mut entries: Vec<_> = fs::read_dir(dir).expect("read web/dist").flatten().collect();
    entries.sort_by_key(|e| e.file_name());
    for entry in entries {
        let path = entry.path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if let Some(rel) = path.strip_prefix(root).ok().and_then(|r| r.to_str())
            && let Some(rel) = rel.strip_suffix(".gz")
        {
            out.push((format!("/{}", rel.replace('\\', "/")), path.clone()));
        }
    }
}

/// The most recently modified file among `paths` (folders are walked).
fn newest(paths: &[PathBuf]) -> Option<(SystemTime, PathBuf)> {
    let mut found: Option<(SystemTime, PathBuf)> = None;
    let mut pending = paths.to_vec();
    while let Some(path) = pending.pop() {
        let Ok(meta) = fs::metadata(&path) else { continue };
        if meta.is_dir() {
            if let Ok(entries) = fs::read_dir(&path) {
                pending.extend(entries.flatten().map(|entry| entry.path()));
            }
        } else if let Ok(time) = meta.modified()
            && found.as_ref().is_none_or(|(newest, _)| time > *newest)
        {
            found = Some((time, path));
        }
    }
    found
}

fn content_type(url: &str) -> &'static str {
    let ext = url.rsplit_once('.').map(|(_, e)| e).unwrap_or("");
    match ext {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" | "map" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "ico" => "image/x-icon",
        "ttf" => "font/ttf",
        "woff" => "font/woff",
        "woff2" => "font/woff2",
        "txt" => "text/plain; charset=utf-8",
        "webmanifest" => "application/manifest+json",
        _ => "application/octet-stream",
    }
}
